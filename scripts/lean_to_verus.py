#!/usr/bin/env python3
"""Generate the Verus specification from Lean.

The Rust half must be checked against *the* specification, not against a second
one that somebody typed in again. So the scalar and boolean definitions of the
integer model are translated mechanically into Verus `spec fn`s, and the result is
checked in and re-generated by CI, which fails if it has drifted.

## What this is, and what it is not

It is a translator for **one file**, over a deliberately small grammar. It is not a
general Lean front end and must never be mistaken for one. Anything outside the
grammar is **refused with an error naming the definition and the token**, never
guessed at — a translator that quietly does its best is worse than no translator,
because the Rust would then verify beautifully against the wrong specification.

It is also *syntactic only*. The one semantically interesting step in this port —
real numbers to integers — happens in `Dpss/IntModel.lean`, where it is proved
(`embed_step`, `intRun_converges`). This script only changes notation.

## What it does not translate, and why

Four kinds of definition are hand-written on the Rust side instead, each citing its
Lean source:

* `advance`, `step`, `run` build a new configuration — structure literals and
  recursion, not arithmetic;
* `timeToNextEvent` is a `Finset.inf'` over `Fin n`;
* `OnPerimeter`, `AdjOrdered`, `EscortsCoherent`, `OnLattice` quantify over `Fin n`
  with a dependent proof argument;
* `Dir` itself is a Rust `enum`.

None of those is arithmetic, which is where a transcription error would hide. The
differential tests cover them end to end.

## Two sources, two shapes

`Dpss/IntModel.lean` describes the **team**, and every definition in it is a
function of the configuration: the translator supplies `c: Snapshot` and, where
the Lean takes a `Fin n`, an `i: int`.

`Dpss/FenceInt.lean` describes **one drone against one wall** (S6a), and its
definitions take their arguments explicitly — a vehicle, a position, a heading.
So the translator reads the binders and emits them, and the grammar carries the
propositional connectives that the safety predicates are built from: `∧`, `∨`,
`¬` and `→` become `&&`, `||`, `!` and `==>`.

The two shapes are `SOURCES` below. Everything else — the tokenizer, the
expression grammar, and the refusal discipline — is shared.

Usage: python3 scripts/lean_to_verus.py [--check]
"""
